const uniKey = u => u[1] + '|' + u[0];
const uniTuition = u => Math.round(u[7] * 1000);
const uniAreas = u => u[8].split(' ');
// области направления (одно направление может входить в две области, например психология)
const fieldAreas = fid => Object.keys(AREAS).filter(a => AREAS[a].f.includes(fid));
// вуз силён в направлении: совпала область или вуз прямо назван в списке направления
function uniFits(u, fid) {
  if (!fid) return true;
  const F = FIELDS[fid];
  if (F && (F.world.some(([n]) => n === u[0]) || F.uz.includes(u[0]))) return true;
  const areas = uniAreas(u);
  return fieldAreas(fid).some(a => areas.includes(a));
}
const findUni = (name, cc) => UNIS.find(u => u[0] === name && (!cc || u[1] === cc));

// Список направлений для выпадающего меню: по областям, по алфавиту внутри
// (психология и экология входят в две области — показываем их один раз, в первой)
function fieldOptions(selected = '', emptyLabel = '') {
  const seen = new Set();
  return (emptyLabel ? `<option value="">${emptyLabel}</option>` : '') + Object.values(AREAS).map(a => {
    const fs = a.f.filter(f => !seen.has(f) && seen.add(f));
    return `<optgroup label="${escapeHtml(tx(a.t))}">${fs.map(f => [f, tx(FIELDS[f].name)]).sort((x, y) => x[1].localeCompare(y[1], LANG))
      .map(([f, n]) => `<option value="${f}" ${f === selected ? 'selected' : ''}>${escapeHtml(n)}</option>`).join('')}</optgroup>`;
  }).join('');
}
